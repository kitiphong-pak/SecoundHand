-- Migration 014: บันทึกเวลาที่ผู้ซื้อชำระเงิน
-- เหตุผล: ออเดอร์เก็บเวลาของทุกขั้นตอนไว้หมด (แจ้งส่งมอบ ยืนยันรับของ ปิดการขาย เปิดข้อพิพาท
-- ยกเลิก) ยกเว้นขั้นชำระเงิน ทำให้ timeline ในหน้าผู้ดูแลกระโดดจาก "สร้างออเดอร์" ไป "แจ้งส่งมอบ"
-- เลย และข้อความยืนยันยกเลิกบอกได้แค่ว่า "เงินที่ชำระไปแล้วจะคืนให้" โดยไม่รู้ว่าชำระเมื่อไหร่

alter table orders add column if not exists paid_at timestamptz;

-- ออเดอร์เก่าที่ชำระไปก่อนมีคอลัมน์นี้ ยังกู้เวลาคืนได้จาก audit log เพราะ route ชำระเงินบันทึก
-- action 'order.paid' ไว้ทุกครั้งตั้งแต่ migration 003 — ใช้รายการแรกสุดของแต่ละออเดอร์
-- (ปกติมีรายการเดียวอยู่แล้ว เพราะจ่ายซ้ำไม่ได้ แต่เผื่อไว้ให้ผลลัพธ์แน่นอนไม่ว่าข้อมูลจะเป็นยังไง)
update orders o
set paid_at = a.first_paid_at
from (
  select target_id, min(created_at) as first_paid_at
  from audit_logs
  where action = 'order.paid' and target_type = 'order'
  group by target_id
) a
where a.target_id = o.id and o.paid_at is null;

-- ออเดอร์ที่ผ่านขั้นชำระเงินมาแล้วแต่ไม่มี audit log (ข้อมูล seed ที่สร้างตรงเข้าฐานข้อมูล)
-- ไม่มีทางรู้เวลาจริง ปล่อยเป็น null ไว้ดีกว่าเดา — ฝั่งแอปถือว่า null = ไม่รู้ แล้วไม่แสดงบรรทัดนั้น
